package java_book.chap_02;

public class _02_DataType {
    public static void main(String[] args) {
        System.out.println("Hello World!"); // 문지열
        System.out.println("안녕하세요?"); // 문자열
        System.out.println(12); // 정수 (int)
        System.out.println(-34); // 정수 (int)
        System.out.println(3.14); // 실수 (double)
        System.out.println(true); // 논리형 (참 true)
        System.out.println(false); // 논리형 (거짓 false)

        System.out.println(123 + 345); // 띄어쓰기 하는게 가독성이 좋음.
    }
}
